"""Generates the Comfort Pack's data mods from config/comfort.toml.

    python tools/make_comfort_pack.py [config/comfort.toml] [out_dir]

Output: Format 3 `.field.json` files (CDUMM, docs/comfort-pack.md) in out_dir (default:
build/comfort-pack). Each one is our own values, built from documented operations only; nothing is
copied from another mod.

Today: stack sizes ([inventory] stack_size_multiplier). A Format 3 `match` sets one value on every
item whose field equals another value, so the multiplier becomes one intent per common stack size
(5 -> 50, 10 -> 100, ...). Items that stack to 1 are left alone. Sizes the game does not use simply
match nothing. Intents run largest first, so a stack that was just raised is never raised again.

UNTESTED against the game until Phase B: check with CDUMM's "Inspect Mod" before shipping.
"""

import json
import sys
import tomllib
from pathlib import Path

# Stack sizes seen in action games of this kind; one that the game does not use is a harmless no-op.
COMMON_STACK_SIZES = [2, 3, 5, 10, 15, 20, 25, 30, 40, 50, 60, 64, 75, 99, 100, 120, 150, 200, 250, 300, 500,
                      999, 1000, 9999]
MAX_STACK = 999_999  # what the biggest stack mods on Nexus use; the field is a u64


def stack_intents(multiplier: float) -> list[dict]:
    if multiplier <= 1.0:
        return []
    intents = []
    for size in sorted(COMMON_STACK_SIZES, reverse=True):
        new = min(MAX_STACK, int(round(size * multiplier)))
        if new > size:
            intents.append({"match": {"max_stack_count": size}, "field": "max_stack_count", "new": new})
    return intents


def field_json(title: str, description: str, target: str, intents: list[dict]) -> dict:
    return {
        "modinfo": {
            "title": title,
            "version": "1.0",
            "author": "Crimson Desert Seamless Co-op+",
            "description": description,
            "note": "Format 3; generated by tools/make_comfort_pack.py from config/comfort.toml",
        },
        "format": 3,
        "target": target,
        "intents": intents,
    }


def main(argv: list[str]) -> int:
    root = Path(__file__).resolve().parent.parent
    cfg_path = Path(argv[1]) if len(argv) > 1 else root / "config" / "comfort.toml"
    out_dir = Path(argv[2]) if len(argv) > 2 else root / "build" / "comfort-pack"
    with open(cfg_path, "rb") as f:
        cfg = tomllib.load(f)
    out_dir.mkdir(parents=True, exist_ok=True)
    written = []
    mult = float(cfg.get("inventory", {}).get("stack_size_multiplier", 1.0))
    intents = stack_intents(mult)
    if intents:
        doc = field_json(f"Co-op+ Comfort: stacks x{mult:g}",
                         f"Every stackable item holds {mult:g} times as much (capped at {MAX_STACK}).",
                         "iteminfo.pabgb", intents)
        path = out_dir / "CoopPlus-Stacks.field.json"
        path.write_text(json.dumps(doc, indent=2) + "\n", encoding="utf-8")
        written.append(path)
    for p in written:
        print(f"wrote {p}")
    if not written:
        print("nothing to write: every Comfort option in this file is at its vanilla value")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
