"""Writes src/mod/net/mission_names.inc from build/ext-save/mission_names.json: {key, "display name"} for every
mission whose display text is a real name (the game's {StaticInfo:...#Name} links reduced to Name).
  python tools/gen/mission_names_inc.py"""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, 'build', 'ext-save', 'mission_names.json')
OUT = os.path.join(ROOT, 'upstream', 'cd-coop-3446', 'src', 'mod', 'net', 'mission_names.inc')
BS = chr(92)


def clean(d):
    d = re.sub(r'\{[^{}#]*#([^{}]*)\}', r'\1', d)  # {StaticInfo:Knowledge:X#Name} -> Name
    d = re.sub(r'\{[^{}]*\}', '', d)               # other tokens
    return ' '.join(d.split())


def c_string(s):
    s = s.encode('ascii', 'replace').decode('ascii')
    return s.replace(BS, BS + BS).replace('"', BS + '"')


rows = []
for e in json.load(open(SRC, encoding='utf-8')):
    d = clean(e.get('display') or '')
    if not d or d == e['name'] or len(d) > 80:
        continue
    kind = 'C' if e['name'].startswith('Challenge_') else 'M' if e['name'].startswith('Mission_') else 'O'
    rows.append((e['key'] & 0xFFFFFFFF, kind, d))
rows.sort()
with open(OUT, 'w', encoding='ascii', newline='\n') as f:
    f.write('// Generated by tools/gen/mission_names_inc.py from the game data (mission key, kind: M mission / C challenge / O other, display name). Do not edit.\n')
    for k, kind, d in rows:
        f.write("{0x%08X, '%s', \"%s\"},\n" % (k, kind, c_string(d)))
print(len(rows), 'missions ->', OUT)
