"""Writes src/mod/net/animal_names.inc from build/ext-save/character_names.json: {character key, points, "name"} for
every wild animal (Animal_*; domestic, trained, ridden and baby animals left out), for the hunting contest.
Points: 3 big or dangerous game, 2 medium, 1 small.
  python tools/gen/animal_names_inc.py"""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, 'build', 'ext-save', 'character_names.json')
OUT = os.path.join(ROOT, 'upstream', 'cd-coop-3446', 'src', 'mod', 'net', 'animal_names.inc')
BS = chr(92)

SKIP = ('Insect', 'Domestic', 'Trained', 'Ride', 'Riding', 'Baby', 'Pet', 'Tamed', 'Summon', 'Dummy', 'Test')
BIG = ('Bear', 'Wolf', 'Boar', 'Lion', 'Tiger', 'Bison', 'Moose', 'Elk', 'Crocodile', 'Rhino', 'Leopard', 'Hyena',
       'Panther', 'Wyvern', 'Mammoth', 'Buffalo')
MEDIUM = ('Deer', 'Fox', 'Goat', 'Sheep', 'Antelope', 'Gazelle', 'Lynx', 'Jackal', 'Coyote', 'Ostrich', 'Camel',
          'Horse', 'Monitor', 'Komodo', 'Cougar', 'Badger', 'Reindeer', 'Ibex', 'Pig')


def c_string(s):
    s = s.encode('ascii', 'replace').decode('ascii')
    return s.replace(BS, BS + BS).replace('"', BS + '"')


rows = []
for key, v in json.load(open(SRC, encoding='utf-8')).items():
    name = v.get('internal', '')
    if not name.startswith('Animal_') or any(w in name for w in SKIP):
        continue
    points = 3 if any(w in name for w in BIG) else 2 if any(w in name for w in MEDIUM) else 1
    clean = v.get('clean') or name
    clean = re.sub(r'^Animal ', '', clean)
    clean = re.sub(r'\b(Wild|Hunt|Normal|Group|Herd)\b', '', clean)
    clean = re.sub(r'\s*\d+$', '', ' '.join(clean.split())).strip() or 'Animal'
    rows.append((int(key) & 0xFFFFFFFF, points, clean))
rows.sort()
with open(OUT, 'w', encoding='ascii', newline='\n') as f:
    f.write('// Generated by tools/gen/animal_names_inc.py from the game data (character key, points, name). Do not edit.\n')
    for k, p, n in rows:
        f.write('{0x%08X, %d, "%s"},\n' % (k, p, c_string(n)))
print(len(rows), 'animals ->', OUT)
