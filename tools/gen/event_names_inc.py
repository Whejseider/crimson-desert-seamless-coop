"""Writes src/mod/net/event_names.inc from build/ext-save/stage_names.json: {stage key, "readable name"} for the
world-event stages (reinforcements, bounty hunters, camp / outpost activity) the host's client starts.
  python tools/gen/event_names_inc.py"""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, 'build', 'ext-save', 'stage_names.json')
OUT = os.path.join(ROOT, 'upstream', 'cd-coop-3446', 'src', 'mod', 'net', 'event_names.inc')
BS = chr(92)
REGIONS = {'Her': 'Hernand', 'Dem': 'Demeniss', 'Del': 'Delesyia', 'Crim': 'Crimson Desert', 'Pai': 'Pailune'}


def words(s):
    s = re.sub(r'([a-z])([A-Z])', r'\1 \2', s.replace('_', ' '))
    return ' '.join(s.split())


def readable(name):
    if name.startswith('Reinforcement_'):
        place = re.sub(r'^Reinforcement_(\dp_)?', '', name)
        return 'Reinforcements at ' + words(place)
    if name.startswith('WantedChaser_'):
        m = re.match(r'WantedChaser_([A-Za-z]+)_Bounty_Hunter_Lv(\d)', name)
        if m:
            return 'Bounty hunters (%s, level %s)' % (m[1], m[2])
        return 'Pursuers: ' + words(name[len('WantedChaser_'):])
    if name.startswith('Node_'):
        parts = name.split('_')
        region = REGIONS.get(parts[1], parts[1]) if len(parts) > 1 else ''
        place = parts[2] if len(parts) > 2 else ''
        kind = 'Patrol' if 'Patrol' in name else 'Monsters' if 'Monster' in name else 'Activity'
        return '%s at %s (%s)' % (kind, words(place), region)
    return None


def c_string(s):
    return s.encode('ascii', 'replace').decode('ascii').replace(BS, BS + BS).replace('"', BS + '"')


rows = []
for key, name in json.load(open(SRC, encoding='utf-8')).items():
    r = readable(name)
    if r:
        rows.append((int(key) & 0xFFFFFFFF, r))
rows.sort()
with open(OUT, 'w', encoding='ascii', newline='\n') as f:
    f.write('// Generated by tools/gen/event_names_inc.py from the game data (stage key, readable name). Do not edit.\n')
    for k, n in rows:
        f.write('{0x%08X, "%s"},\n' % (k, c_string(n)))
print(len(rows), 'event stages ->', OUT)
